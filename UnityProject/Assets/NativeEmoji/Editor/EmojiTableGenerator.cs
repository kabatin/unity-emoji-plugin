using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;
using UnityEngine.Networking;

namespace NativeEmoji.Editor
{
    /// <summary>
    /// Unicode の emoji-data.txt から絵文字判定テーブルを生成する。
    ///
    /// 絵文字ブロックを手書きの範囲で近似すると、絵文字でない文字
    /// （錬金術記号・囲み英数字など）を巻き込んだり、
    /// Emoji_Presentation=No の絵文字を取りこぼしたりする。
    /// 原典データから生成することでそれを防ぐ。
    /// </summary>
    public static class EmojiTableGenerator
    {
        private const string SourceUrl =
            "https://www.unicode.org/Public/UCD/latest/ucd/emoji/emoji-data.txt";

        private const string OutputFileName = "EmojiCodepointTables.cs";

        private static readonly Regex EntryPattern = new Regex(
            @"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)",
            RegexOptions.Compiled);

        [MenuItem("Tools/Native Emoji/Regenerate Codepoint Tables")]
        public static void Regenerate()
        {
            string data = Download();
            if (data == null)
                return;

            string outputPath = ResolveOutputPath();
            if (outputPath == null)
            {
                Debug.LogError(
                    $"EmojiTableGenerator: {OutputFileName} が見つからないため、書き出し先を決められない");
                return;
            }

            try
            {
                string generated = Generate(data);
                File.WriteAllText(Path.GetFullPath(outputPath), generated);
                AssetDatabase.Refresh();

                Debug.Log($"EmojiTableGenerator: {outputPath} を更新した");
            }
            catch (UnauthorizedAccessException)
            {
                // UPM でインストールした場合、パッケージは読み取り専用の場所に展開される
                Debug.LogError(
                    $"EmojiTableGenerator: {outputPath} に書き込めない。\n" +
                    "UPM でインストールしたパッケージは読み取り専用なので、" +
                    "再生成はリポジトリを clone した作業用プロジェクトで行う");
            }
            catch (Exception e)
            {
                Debug.LogError($"EmojiTableGenerator: 生成に失敗した - {e.Message}");
            }
        }

        /// <summary>
        /// 生成先を既存アセットの位置から決める。
        /// Assets 配下・埋め込みパッケージ・UPM のいずれに置かれていても追従する。
        /// </summary>
        private static string ResolveOutputPath()
        {
            foreach (string guid in AssetDatabase.FindAssets($"{Path.GetFileNameWithoutExtension(OutputFileName)} t:MonoScript"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (path.EndsWith("/" + OutputFileName, StringComparison.Ordinal))
                {
                    return path;
                }
            }

            return null;
        }

        private static string Download()
        {
            using (UnityWebRequest request = UnityWebRequest.Get(SourceUrl))
            {
                request.SendWebRequest();

                try
                {
                    while (!request.isDone)
                    {
                        bool canceled = EditorUtility.DisplayCancelableProgressBar(
                            "Native Emoji",
                            "emoji-data.txt をダウンロード中...",
                            request.downloadProgress);

                        if (canceled)
                        {
                            request.Abort();
                            return null;
                        }
                    }
                }
                finally
                {
                    EditorUtility.ClearProgressBar();
                }

                if (request.result != UnityWebRequest.Result.Success)
                {
                    Debug.LogError(
                        $"EmojiTableGenerator: ダウンロードに失敗した - {request.error}\n{SourceUrl}");
                    return null;
                }

                return request.downloadHandler.text;
            }
        }

        /// <summary>
        /// emoji-data.txt の本文から C# ソースを組み立てる。
        /// </summary>
        public static string Generate(string data)
        {
            if (string.IsNullOrEmpty(data))
                throw new ArgumentException("emoji-data.txt が空", nameof(data));

            string version = ExtractHeader(data, "Version") ?? "unknown";
            string date = ExtractHeader(data, "Date") ?? "unknown";

            List<(int start, int end)> emoji = ParseProperty(data, "Emoji");
            List<(int start, int end)> presentation = ParseProperty(data, "Emoji_Presentation");

            if (emoji.Count == 0 || presentation.Count == 0)
                throw new InvalidDataException("プロパティを 1 つも読み取れなかった");

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//     このファイルは Unicode の emoji-data.txt から生成されている。手で編集しない。");
            sb.AppendLine("//");
            sb.AppendLine($"//     生成元: {SourceUrl}");
            sb.AppendLine($"//     UTS #51 Version: {version}");
            sb.AppendLine($"//     Data Date: {date}");
            sb.AppendLine("//");
            sb.AppendLine("//     再生成: Unity メニューの Tools > Native Emoji > Regenerate Codepoint Tables");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("namespace NativeEmoji");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Unicode の絵文字プロパティを範囲テーブルとして保持する。");
            sb.AppendLine("    ///");
            sb.AppendLine("    /// - <c>Emoji</c>: 絵文字になり得るコードポイント");
            sb.AppendLine("    /// - <c>Emoji_Presentation</c>: 修飾子なしで既定が絵文字表示になるコードポイント");
            sb.AppendLine("    ///");
            sb.AppendLine("    /// 範囲は昇順にマージ済みなので、二分探索で判定できる。");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static class EmojiCodepointTables");
            sb.AppendLine("    {");
            sb.AppendLine("        /// <summary>生成元データの UTS #51 バージョン</summary>");
            sb.AppendLine($"        public const string UnicodeVersion = \"{version}\";");
            sb.AppendLine();
            AppendTable(sb, "EmojiProperty", emoji);
            sb.AppendLine();
            AppendTable(sb, "EmojiPresentationProperty", presentation);
            sb.AppendLine();
            sb.AppendLine("        /// <summary>");
            sb.AppendLine("        /// Unicode の Emoji プロパティを持つか");
            sb.AppendLine("        /// </summary>");
            sb.AppendLine("        public static bool HasEmojiProperty(int codepoint)");
            sb.AppendLine("        {");
            sb.AppendLine("            return Contains(EmojiProperty, codepoint);");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>");
            sb.AppendLine("        /// Unicode の Emoji_Presentation プロパティを持つか");
            sb.AppendLine("        /// （修飾子なしで既定が絵文字表示）");
            sb.AppendLine("        /// </summary>");
            sb.AppendLine("        public static bool HasEmojiPresentationProperty(int codepoint)");
            sb.AppendLine("        {");
            sb.AppendLine("            return Contains(EmojiPresentationProperty, codepoint);");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>");
            sb.AppendLine("        /// [start, end, start, end, ...] の昇順テーブルを二分探索する");
            sb.AppendLine("        /// </summary>");
            sb.AppendLine("        private static bool Contains(int[] ranges, int codepoint)");
            sb.AppendLine("        {");
            sb.AppendLine("            int low = 0;");
            sb.AppendLine("            int high = ranges.Length / 2 - 1;");
            sb.AppendLine();
            sb.AppendLine("            while (low <= high)");
            sb.AppendLine("            {");
            sb.AppendLine("                int mid = (low + high) / 2;");
            sb.AppendLine("                int start = ranges[mid * 2];");
            sb.AppendLine("                int end = ranges[mid * 2 + 1];");
            sb.AppendLine();
            sb.AppendLine("                if (codepoint < start)");
            sb.AppendLine("                    high = mid - 1;");
            sb.AppendLine("                else if (codepoint > end)");
            sb.AppendLine("                    low = mid + 1;");
            sb.AppendLine("                else");
            sb.AppendLine("                    return true;");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            return false;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static string ExtractHeader(string data, string key)
        {
            Match match = Regex.Match(data, $@"^# {key}: (.+)$", RegexOptions.Multiline);
            return match.Success ? match.Groups[1].Value.Trim() : null;
        }

        /// <summary>
        /// 指定プロパティの範囲を読み取り、昇順にマージして返す。
        /// </summary>
        private static List<(int start, int end)> ParseProperty(string data, string property)
        {
            var ranges = new List<(int start, int end)>();

            foreach (string rawLine in data.Split('\n'))
            {
                string line = rawLine.Split('#')[0].Trim();
                if (line.Length == 0)
                    continue;

                Match match = EntryPattern.Match(line);
                if (!match.Success || match.Groups[3].Value != property)
                    continue;

                int start = int.Parse(match.Groups[1].Value, NumberStyles.HexNumber);
                int end = match.Groups[2].Success
                    ? int.Parse(match.Groups[2].Value, NumberStyles.HexNumber)
                    : start;

                ranges.Add((start, end));
            }

            return Merge(ranges);
        }

        /// <summary>
        /// 範囲を昇順に並べ、隣接・重複するものを 1 つにまとめる。
        /// </summary>
        private static List<(int start, int end)> Merge(List<(int start, int end)> ranges)
        {
            ranges.Sort((a, b) => a.start.CompareTo(b.start));

            var merged = new List<(int start, int end)>();

            foreach ((int start, int end) in ranges)
            {
                if (merged.Count > 0 && start <= merged[merged.Count - 1].end + 1)
                {
                    (int prevStart, int prevEnd) = merged[merged.Count - 1];
                    merged[merged.Count - 1] = (prevStart, Math.Max(prevEnd, end));
                }
                else
                {
                    merged.Add((start, end));
                }
            }

            return merged;
        }

        private static void AppendTable(StringBuilder sb, string name,
                                        List<(int start, int end)> ranges)
        {
            sb.AppendLine($"        private static readonly int[] {name} =");
            sb.AppendLine("        {");

            for (int i = 0; i < ranges.Count; i += 4)
            {
                var line = new StringBuilder("            ");

                for (int j = i; j < Math.Min(i + 4, ranges.Count); j++)
                {
                    line.Append($"0x{ranges[j].start:X5}, 0x{ranges[j].end:X5}");
                    if (j < ranges.Count - 1)
                        line.Append(",");
                    if (j < Math.Min(i + 4, ranges.Count) - 1)
                        line.Append(" ");
                }

                sb.AppendLine(line.ToString());
            }

            sb.AppendLine("        };");
        }
    }
}
